// Map locale prefix → translation key (for lookup fallback)
export function getTranslations(locale) {
  if (!locale) return TRANSLATIONS[DEFAULT_LANG];
  // Exact match first
  if (TRANSLATIONS[locale]) return TRANSLATIONS[locale];
  // Language-only fallback (e.g. 'es-AR' → 'es-ES')
  const lang = locale.split('-')[0];
  const match = Object.keys(TRANSLATIONS).find(k => k.startsWith(lang + '-'));
  return TRANSLATIONS[match] || TRANSLATIONS[DEFAULT_LANG];
}
